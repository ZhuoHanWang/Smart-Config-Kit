'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const { execFileSync } = require('node:child_process');

const ROOT = path.resolve(__dirname, '../..');
const SNAPSHOT_FILE = path.join(ROOT, 'rulesets/generated/egern-traffic-snapshot.json.gz');
const FUSED_DIR = path.join(ROOT, 'rulesets/generated/fused/mihomo');

function hash(text) {
  return crypto.createHash('sha256').update(String(text).replace(/\r\n/g, '\n'), 'utf8').digest('hex');
}

function gitShow(relative) {
  return execFileSync('git', ['show', `HEAD:${relative.replace(/\\/g, '/')}`], { cwd: ROOT, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });
}

function currentFusedHashes() {
  const records = {};
  for (const file of fs.readdirSync(FUSED_DIR).filter((name) => name.endsWith('.yaml')).sort()) {
    records[file] = hash(fs.readFileSync(path.join(FUSED_DIR, file), 'utf8'));
  }
  return records;
}

function sourceBindings() {
  const { trafficSourceFingerprint, fusedPayloadReceipt } = require('../build-fused-rule-sets');
  return {
    trafficSourceFingerprint: trafficSourceFingerprint(),
    fusedPayloadFingerprint: fusedPayloadReceipt().digest,
  };
}

function packSnapshot(manifest, readAsset, publishedManifestText) {
  const assets = {};
  for (const record of manifest.assets.files) {
    const text = readAsset(record.file).replace(/\r\n/g, '\n');
    if (hash(text) !== record.sha256 || Buffer.byteLength(text, 'utf8') !== record.bytes) {
      throw new Error(`Published Egern asset differs from manifest: ${record.file}`);
    }
    assets[record.file] = text;
  }
  return {
    schemaVersion: 1,
    publishedManifestSha256: hash(publishedManifestText),
    publishedSource: manifest.source,
    publishedRendered: manifest.rendered,
    publishedAssets: manifest.assets.files,
    ...sourceBindings(),
    fusedMihomoHashes: currentFusedHashes(),
    assets,
  };
}

function saveSnapshot(snapshot) {
  const temporary = `${SNAPSHOT_FILE}.tmp-${process.pid}`;
  try {
    fs.writeFileSync(temporary, zlib.gzipSync(Buffer.from(JSON.stringify(snapshot), 'utf8'), { level: 9, mtime: 0 }));
    fs.renameSync(temporary, SNAPSHOT_FILE);
  } finally {
    if (fs.existsSync(temporary)) fs.rmSync(temporary);
  }
  return { file: SNAPSHOT_FILE, count: Object.keys(snapshot.assets).length, bytes: fs.statSync(SNAPSHOT_FILE).size };
}

function adoptPublishedHead() {
  if (fs.existsSync(SNAPSHOT_FILE)) throw new Error(`Snapshot already exists: ${SNAPSHOT_FILE}`);
  const manifestText = gitShow('rulesets/generated/egern/manifest.json');
  const manifest = JSON.parse(manifestText);
  return saveSnapshot(packSnapshot(manifest, (file) => gitShow(`rulesets/generated/egern/${file}`), manifestText));
}

function freezeCurrentOutput() {
  const manifestText = fs.readFileSync(path.join(ROOT, 'rulesets/generated/egern/manifest.json'), 'utf8');
  const manifest = JSON.parse(manifestText);
  return saveSnapshot(packSnapshot(manifest, (file) => fs.readFileSync(path.join(ROOT, 'rulesets/generated/egern', file), 'utf8'), manifestText));
}

function freezeStagedOutput(directory, manifest) {
  const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
  return saveSnapshot(packSnapshot(manifest, (file) => fs.readFileSync(path.join(directory, file), 'utf8'), manifestText));
}

function packStagedOutput(directory, manifest) {
  const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
  return packSnapshot(manifest, (file) => fs.readFileSync(path.join(directory, file), 'utf8'), manifestText);
}

function loadSnapshot() {
  const snapshot = JSON.parse(zlib.gunzipSync(fs.readFileSync(SNAPSHOT_FILE)).toString('utf8'));
  if (snapshot.schemaVersion !== 1 || !snapshot.assets || !snapshot.fusedMihomoHashes) throw new Error('Invalid Egern traffic snapshot');
  const fused = currentFusedHashes();
  if (JSON.stringify(fused) !== JSON.stringify(snapshot.fusedMihomoHashes)) {
    throw new Error('Egern snapshot fused payload fingerprint mismatch; full rule refresh required');
  }
  const bindings = sourceBindings();
  if (snapshot.trafficSourceFingerprint !== bindings.trafficSourceFingerprint ||
      snapshot.fusedPayloadFingerprint !== bindings.fusedPayloadFingerprint) {
    throw new Error('Egern snapshot traffic source or fused payload fingerprint mismatch; full rule refresh required');
  }
  for (const [file, text] of Object.entries(snapshot.assets)) {
    if (!/^[a-z0-9][a-z0-9._-]*\.yaml$/.test(file) || !text.startsWith('# Generated by tools/generate-egern-from-cmfa.js\n')) {
      throw new Error(`Invalid Egern snapshot asset: ${file}`);
    }
  }
  if (!Array.isArray(snapshot.publishedAssets) || snapshot.publishedAssets.length !== Object.keys(snapshot.assets).length) {
    throw new Error('Egern snapshot inventory is incomplete');
  }
  for (const record of snapshot.publishedAssets) {
    const text = snapshot.assets[record.file];
    if (typeof text !== 'string' || hash(text) !== record.sha256 || Buffer.byteLength(text, 'utf8') !== record.bytes) {
      throw new Error(`Egern snapshot asset hash mismatch: ${record.file}`);
    }
  }
  return snapshot;
}

if (require.main === module && process.argv.includes('--adopt-head')) {
  try { console.log(JSON.stringify(adoptPublishedHead())); } catch (error) { console.error(error.message); process.exitCode = 1; }
}

module.exports = { SNAPSHOT_FILE, adoptPublishedHead, currentFusedHashes, freezeCurrentOutput, freezeStagedOutput, packStagedOutput, saveSnapshot, hash, loadSnapshot };
